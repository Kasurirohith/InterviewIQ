import os
import re
import sqlite3


DATABASE_URL = os.getenv("DATABASE_URL", "").strip()


if DATABASE_URL:
    # Supabase (and other PostgreSQL hosts) provide a PostgreSQL connection URL
    # through DATABASE_URL. Keep the connection and cursor interface used by
    # app.py so SQLite remains available for local development.
    import psycopg

    class PostgresCursor:
        def __init__(self, raw_cursor):
            self.raw_cursor = raw_cursor

        def execute(self, query, parameters=()):
            # The existing application uses SQLite's qmark placeholders.
            self.raw_cursor.execute(re.sub(r"\?", "%s", query), parameters)
            return self

        def fetchone(self):
            return self.raw_cursor.fetchone()

        def fetchall(self):
            return self.raw_cursor.fetchall()

        @property
        def rowcount(self):
            return self.raw_cursor.rowcount

        @property
        def description(self):
            description = self.raw_cursor.description
            if description is None:
                return None
            return [(column.name,) for column in description]

    conn = psycopg.connect(DATABASE_URL, connect_timeout=10)
    cursor = PostgresCursor(conn.cursor())

    # PostgreSQL schema. IF NOT EXISTS makes startup safe on later deploys.
    cursor.execute("""
    CREATE TABLE IF NOT EXISTS users (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        name TEXT,
        email TEXT UNIQUE,
        password TEXT
    )
    """)
    cursor.execute("""
    CREATE TABLE IF NOT EXISTS interview_history (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        email TEXT,
        ats_score INTEGER,
        interview_score INTEGER,
        created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
        company TEXT NOT NULL DEFAULT '',
        track TEXT NOT NULL DEFAULT '',
        answers_json TEXT NOT NULL DEFAULT '[]'
    )
    """)
    cursor.execute("""
    CREATE TABLE IF NOT EXISTS subscriptions (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        name TEXT NOT NULL,
        email TEXT NOT NULL,
        plan_code TEXT NOT NULL,
        plan_name TEXT NOT NULL,
        category TEXT NOT NULL,
        list_price DOUBLE PRECISION NOT NULL,
        discount_percent INTEGER NOT NULL,
        demo_amount DOUBLE PRECISION NOT NULL,
        payment_method TEXT NOT NULL,
        payment_reference TEXT NOT NULL,
        transaction_id TEXT NOT NULL DEFAULT '',
        payment_status TEXT NOT NULL DEFAULT 'demo_paid',
        status TEXT NOT NULL DEFAULT 'active',
        created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
        updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
    )
    """)
    # Also migrate databases created before detailed feedback was stored.
    cursor.execute("ALTER TABLE interview_history ADD COLUMN IF NOT EXISTS company TEXT NOT NULL DEFAULT ''")
    cursor.execute("ALTER TABLE interview_history ADD COLUMN IF NOT EXISTS track TEXT NOT NULL DEFAULT ''")
    cursor.execute("ALTER TABLE interview_history ADD COLUMN IF NOT EXISTS answers_json TEXT NOT NULL DEFAULT '[]'")
    cursor.execute("ALTER TABLE subscriptions ADD COLUMN IF NOT EXISTS transaction_id TEXT NOT NULL DEFAULT ''")
    cursor.execute("CREATE UNIQUE INDEX IF NOT EXISTS idx_subscriptions_transaction_id ON subscriptions(transaction_id) WHERE transaction_id <> ''")
else:
    # Local development defaults to a SQLite file beside this module. A custom
    # path is useful for any persistent volume mounted at runtime.
    DB_PATH = os.path.abspath(
        os.environ.get("DATABASE_PATH")
        or os.path.join(os.path.dirname(__file__), "auth.db")
    )
    os.makedirs(os.path.dirname(DB_PATH), exist_ok=True)
    conn = sqlite3.connect(DB_PATH, check_same_thread=False)
    cursor = conn.cursor()

    cursor.execute("""
    CREATE TABLE IF NOT EXISTS users (
        id INTEGER PRIMARY KEY AUTOINCREMENT,
        name TEXT,
        email TEXT UNIQUE,
        password TEXT
    )
    """)
    cursor.execute("""
    CREATE TABLE IF NOT EXISTS interview_history (
        id INTEGER PRIMARY KEY AUTOINCREMENT,
        email TEXT,
        ats_score INTEGER,
        interview_score INTEGER,
        created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
    )
    """)

    # Migrate old local SQLite databases in place without deleting score history.
    for column_name, column_type in (
        ("company", "TEXT NOT NULL DEFAULT ''"),
        ("track", "TEXT NOT NULL DEFAULT ''"),
        ("answers_json", "TEXT NOT NULL DEFAULT '[]'"),
    ):
        cursor.execute("PRAGMA table_info(interview_history)")
        existing_columns = {row[1] for row in cursor.fetchall()}
        if column_name not in existing_columns:
            cursor.execute(
                f"ALTER TABLE interview_history ADD COLUMN {column_name} {column_type}"
            )

    cursor.execute("""
    CREATE TABLE IF NOT EXISTS subscriptions (
        id INTEGER PRIMARY KEY AUTOINCREMENT,
        name TEXT NOT NULL,
        email TEXT NOT NULL,
        plan_code TEXT NOT NULL,
        plan_name TEXT NOT NULL,
        category TEXT NOT NULL,
        list_price REAL NOT NULL,
        discount_percent INTEGER NOT NULL,
        demo_amount REAL NOT NULL,
        payment_method TEXT NOT NULL,
        payment_reference TEXT NOT NULL,
        transaction_id TEXT NOT NULL DEFAULT '',
        payment_status TEXT NOT NULL DEFAULT 'demo_paid',
        status TEXT NOT NULL DEFAULT 'active',
        created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
        updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
    )
    """)

    cursor.execute("PRAGMA table_info(subscriptions)")
    subscription_columns = {row[1] for row in cursor.fetchall()}
    if "transaction_id" not in subscription_columns:
        cursor.execute("ALTER TABLE subscriptions ADD COLUMN transaction_id TEXT NOT NULL DEFAULT ''")
    cursor.execute("CREATE UNIQUE INDEX IF NOT EXISTS idx_subscriptions_transaction_id ON subscriptions(transaction_id) WHERE transaction_id <> ''")

conn.commit()
